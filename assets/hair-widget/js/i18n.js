export function normalizeLocale(locale) {
  const code = String(locale || 'en').toLowerCase().replace('_', '-').split('-')[0];
  return Object.prototype.hasOwnProperty.call(TRANSLATIONS, code) ? code : 'en';
}

export function getHairWidgetCopy(locale) {
  const code = normalizeLocale(locale);
  const localized = TRANSLATIONS[code] || {};
  return Object.freeze({
    ...EN,
    ...localized,
    steps: localized.steps || EN.steps,
    face: Object.freeze({ ...EN.face, ...(localized.face || {}) }),
  });
}
