/** Whether the current front-end request is Spanish. */
function estecapelli_is_spanish_request() {
	$language = (string) apply_filters( 'wpml_current_language', null );
	if ( function_exists( 'estecapelli_indexed_language_code' ) ) {
		return 'es' === estecapelli_indexed_language_code( $language );
	}
	if ( $language ) {
		return 'es' === $language;
	}

	return 0 === strpos( determine_locale(), 'es_' );
}

