add_filter( 'ngettext', 'estecapelli_es_ngettext_fallback', 25, 5 );
/** Translate pluralised template labels without changing article content. */
function estecapelli_es_ngettext_fallback( $translation, $single, $plural, $number, $domain ) {
	if (
		'estecapelli' === $domain &&
		estecapelli_is_spanish_request() &&
		in_array( $translation, array( $single, $plural ), true )
	) {
		if ( '%d min read' === $single && '%d min read' === $plural ) {
			return '%d min de lectura';
		}
		if ( '%d star' === $single && '%d stars' === $plural ) {
			return 1 === (int) $number ? '%d estrella' : '%d estrellas';
		}
	}

	return $translation;
}
