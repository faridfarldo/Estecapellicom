			'This page could not be found' => 'Această pagină nu a putut fi găsită',
			'The page you are looking for may have been moved or no longer exists. You can head back to the homepage, or pick one of the sections below.' => 'Pagina pe care o cauți s-ar putea să fi fost mutată sau să nu mai existe. Poți reveni la pagina principală sau poți alege una dintre secțiunile de mai jos.',
			'Back to homepage' => 'Înapoi la pagina principală',
			'Contact us' => 'Contactează-ne',
			'Popular sections' => 'Secțiuni populare',
			'Site sections' => 'Secțiunile site-ului',
		);
	}

	return $strings[ $text ] ?? $translation;
}

add_filter( 'ngettext', 'estecapelli_ro_ngettext_fallback', 25, 5 );
/** Translate pluralised template labels without changing article content. */
function estecapelli_ro_ngettext_fallback( $translation, $single, $plural, $number, $domain ) {
	if (
		'estecapelli' === $domain &&
		estecapelli_is_romanian_request() &&
		in_array( $translation, array( $single, $plural ), true )
	) {
		if ( '%d min read' === $single && '%d min read' === $plural ) {
			return '%d min de lectură';
		}
		if ( '%d star' === $single && '%d stars' === $plural ) {
			// Ratings only ever run 1–5, so the "de stele" form from 20 up
			// never applies here.
			return 1 === (int) $number ? '%d stea' : '%d stele';
		}
	}

	return $translation;
}
