/** Whether the current request is the indexed Romanian language. */
function estecapelli_is_romanian_request() {
	// The URL is the contract and is checked first: WPML answers with the
	// site's DEFAULT language wherever it cannot resolve a request — most
	// visibly on a 404 — which would render the Romanian error page in
	// English. This is the same trap /pt/ fell into.
	if ( function_exists( 'estecapelli_request_language_code' ) ) {
		$requested = estecapelli_request_language_code();
		if ( '' !== $requested ) {
			return 'ro' === $requested;
		}
	}

	$language = (string) apply_filters( 'wpml_current_language', null );
	if ( function_exists( 'estecapelli_indexed_language_code' ) ) {
		return 'ro' === estecapelli_indexed_language_code( $language );
	}

	return 'ro' === strtolower( str_replace( '_', '-', $language ) );
}

